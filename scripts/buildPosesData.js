// Helper to add pose
function addPose(p) {
  poses.push({
    id: p.id,
    categoryId: p.categoryId,
    category: p.category || (categories.find(c => c.id === p.categoryId)?.name || p.categoryId),
    title: p.title,
    description: p.description,
    imageUrl: p.imageUrl,
    thumbnailUrl: p.thumbnailUrl || p.imageUrl,
    overlayImage: '',
    difficulty: p.difficulty || 'easy',
    indoor: p.indoor ?? false,
    tags: p.tags || [p.categoryId, 'photography', 'pose'],
    views: p.views || Math.floor(Math.random() * 15000) + 5000,
    downloads: p.downloads || Math.floor(Math.random() * 6000) + 2000,
    favorites: p.favorites || Math.floor(Math.random() * 5000) + 1500,
    estimatedDistance: p.estimatedDistance || 2.2,
    cameraAngle: p.cameraAngle || 'eye-level',
    lighting: p.lighting || 'natural daylight',
    orientation: p.orientation || 'portrait',
    createdAt: '2026-08-18T00:00:00Z',
    updatedAt: '2026-08-18T00:00:00Z',
    instructions: p.instructions || [
      'Position yourself with shoulders relaxed and natural posture.',
      'Shift 70% weight onto the back foot for natural silhouette balance.',
      'Turn torso 30-45 degrees towards the key light.',
      'Maintain soft eye contact with camera or glance slightly off-lens.',
    ],
    tips: p.tips || [
      'Keep posture loose and natural.',
      'Use natural ambient lighting for organic depth.',
    ],
    ...(p.poseDna ? { poseDna: p.poseDna } : {})
  });
}

