// Helper: get templates by category
export function getTemplatesByCategory(category: string): Template[] {
  if (category === 'all') return TEMPLATE_DATASET;
  return TEMPLATE_DATASET.filter((t) => t.category === category);
}

// Helper: get featured templates
export function getFeaturedTemplates(): Template[] {
  return TEMPLATE_DATASET.filter((t) => t.isFeatured);
}

// Helper: get new templates
export function getNewTemplates(): Template[] {
  return TEMPLATE_DATASET.filter((t) => t.isNew);
}

// Helper: get template by ID
export function getTemplateById(id: string): Template | undefined {
  return TEMPLATE_DATASET.find((t) => t.id === id);
}
